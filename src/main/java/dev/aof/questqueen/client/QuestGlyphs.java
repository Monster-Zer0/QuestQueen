    public static boolean isKnown(String id) {
        return QuestGlyphIds.isKnown(id);
    }

    public static void draw(GuiGraphics graphics, String id, int x, int y, int color) {
        draw(graphics, id, x, y, 16, color);
    }

    public static void draw(GuiGraphics graphics, String id, int x, int y, int px, int color) {
        if (!isKnown(id) || px <= 0) {
            return;
        }
        var pose = graphics.pose();
        pose.pushPose();
        pose.translate(x, y, 0);
        if (px != 16) {
            float scale = px / 16f;
            pose.scale(scale, scale, 1f);
        }
        String[] rows = pattern(id);
        if (rows != null) {
            for (int row = 0; row < 16; row++) {
                String line = rows[row];
                for (int col = 0; col < 16 && col < line.length(); col++) {
                    if (line.charAt(col) != '.') {
                        MockChrome.box(graphics, col, row, 1, 1, color);
                    }
                }
            }
        }
        pose.popPose();
    }

