export function glyphSvg(id: string, color = "#f5f0e0"): string {
  const rows = PATTERNS[id];
  if (!rows) return "";
  const rects: string[] = [];
  for (let y = 0; y < rows.length; y++) {
    const line = rows[y];
    for (let x = 0; x < line.length; x++) {
      if (line[x] !== ".") rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${color}"/>`);
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" shape-rendering="crispEdges">${rects.join("")}</svg>`;
}

export function glyphPickerHtml(selected: string, disabled: boolean, id: string): string {
  const buttons = GLYPH_IDS.map((glyph) => {
    const on = selected === glyph ? " selected" : "";
    return `<button type="button" class="glyph-thumb${on}" data-glyph="${glyph}" data-glyph-host="${id}" ${disabled ? "disabled" : ""} title="${glyph}">${glyphSvg(glyph)}</button>`;
  }).join("");
  return `
    <label>QUESTQUEEN GLYPH</label>
    <div class="glyph-pack" id="${id}" data-value="${selected}">
      <button type="button" class="glyph-thumb${selected ? "" : " selected"}" data-glyph="" data-glyph-host="${id}" ${disabled ? "disabled" : ""} title="Use Minecraft item">×</button>
      ${buttons}
    </div>
  `;
}

export function readGlyph(root: HTMLElement, hostId: string): string {
  const host = root.querySelector<HTMLElement>(hostId);
  return (host?.dataset.value ?? "").trim();
}

export function wireGlyphPicker(root: HTMLElement, hostId: string, onChange: () => void): void {
  const host = root.querySelector<HTMLElement>(hostId);
  if (!host) return;
  host.querySelectorAll<HTMLButtonElement>("[data-glyph]").forEach((button) => {
    button.addEventListener("click", () => {
      const value = button.dataset.glyph ?? "";
      host.dataset.value = value;
      host.querySelectorAll(".glyph-thumb").forEach((el) => el.classList.toggle("selected", el === button));
      onChange();
    });
  });
}

export function previewIntroHtml(body: string): string {
  const lines = (body ?? "").replace(/\r\n/g, "\n").split("\n");
  const html: string[] = [];
  for (const raw of lines) {
    if (!raw.trim()) {
      html.push('<div class="intro-gap"></div>');
      continue;
    }
    let heading = "";
    let rest = raw;
    if (rest.startsWith("##")) {
      heading = "h3";
      rest = rest.slice(2).replace(/^ /, "");
    } else if (rest.startsWith("#")) {
      heading = "h2";
      rest = rest.slice(1).replace(/^ /, "");
    }
    let inner = rest
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
    inner = inner.replace(/\{#([0-9A-Fa-f]{6})\}([\s\S]*?)\{\/#\}/g, '<span style="color:#$1">$2</span>');
    inner = inner.replace(/\{size:(\d+)\}([\s\S]*?)\{\/size\}/g, (_m, n: string, text: string) => {
      const size = Math.max(8, Math.min(24, Number(n)));
      return `<span style="font-size:${size}px">${text}</span>`;
    });
    inner = inner.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
    inner = inner.replace(/\*([^*]+)\*/g, "<em>$1</em>");
    html.push(heading ? `<${heading}>${inner}</${heading}>` : `<p>${inner}</p>`);
  }
  return html.join("");
}
